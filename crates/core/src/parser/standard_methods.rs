/// Each language's standard methods, by the language's key.
static STANDARD_METHODS: LazyLock<Vec<(&'static [&'static str], HashSet<&'static str>)>> =
    LazyLock::new(|| {
        let set = |lists: &[&[&'static str]]| -> HashSet<&'static str> {
            lists.iter().flat_map(|list| list.iter().copied()).collect()
        };
        vec![
            (&["rust"][..], set(&[RUST])),
            (&["python"][..], set(&[PYTHON])),
            (
                &["javascript", "typescript", "tsx", "vue", "svelte"][..],
                set(&[JAVASCRIPT]),
            ),
            (&["java"][..], set(&[JAVA])),
            (&["kotlin"][..], set(&[JAVA, KOTLIN])),
            (&["scala"][..], set(&[JAVA, SCALA])),
            (&["c_sharp", "vb_net", "fsharp"][..], set(&[DOTNET])),
            (&["go"][..], set(&[GO])),
            (&["c", "cpp", "cuda"][..], set(&[CPP])),
            (&["swift"][..], set(&[SWIFT])),
            (&["dart"][..], set(&[DART])),
            (&["ruby"][..], set(&[RUBY])),
            (&["php"][..], set(&[PHP])),
        ]
    });

/// Whether `name` is a method `language`'s standard types have — `len`,
/// `push` and `path` in Rust, `append` in Python, `forEach` in JavaScript —
/// which a call through a value of a type the index cannot tell is taken to
/// be of. A language with no list (Solidity, Bash, SQL, …) has none.
#[must_use]
pub fn is_standard_method(name: &str, language: &str) -> bool {
    STANDARD_METHODS
        .iter()
        .find(|(languages, _)| languages.contains(&language))
        .is_some_and(|(_, methods)| methods.contains(name))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Each list is sorted and without repeats, so a name is easy to find and
    /// none is listed twice.
    #[test]
    fn every_list_is_sorted_and_without_repeats() {
        for (name, list) in [
            ("RUST", RUST),
            ("PYTHON", PYTHON),
            ("JAVASCRIPT", JAVASCRIPT),
            ("JAVA", JAVA),
            ("KOTLIN", KOTLIN),
            ("SCALA", SCALA),
            ("DOTNET", DOTNET),
            ("GO", GO),
            ("CPP", CPP),
            ("SWIFT", SWIFT),
            ("DART", DART),
            ("RUBY", RUBY),
            ("PHP", PHP),
        ] {
            assert!(
                list.windows(2).all(|pair| pair[0] < pair[1]),
                "{name} is not sorted or repeats a name"
            );
        }
    }

    #[test]
    fn a_language_has_its_own_standard_methods() {
        assert!(is_standard_method("len", "rust"));
        assert!(is_standard_method("append", "python"));
        assert!(is_standard_method("forEach", "tsx"));
        assert!(is_standard_method("isNotEmpty", "kotlin"));
        assert!(is_standard_method("size", "kotlin"));
        assert!(is_standard_method("Add", "fsharp"));
        assert!(!is_standard_method("len", "python"));
        assert!(!is_standard_method("text_content", "rust"));
        assert!(!is_standard_method("len", "solidity"));
    }
}
