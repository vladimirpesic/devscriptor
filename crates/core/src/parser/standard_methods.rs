//! The methods of each language's standard types — its collections, strings,
//! paths, files, options and futures — that code calls on values.
//!
//! A call through a value (`items.len()`, `dir.path()`) is of a method of the
//! value's type, which the index cannot tell. Resolved by name alone, such a
//! call would be linked to whichever project method shares the name: in a
//! Rust workspace, `is_empty`, `path`, `len`, `get`, `as_str`, `push` and
//! `iter` make more than half of the edges so guessed, nearly all of them to a
//! project type the value is not. A call of one of these names is taken to be
//! of the standard type's method unless the value is named after a project
//! type that has it (see [`CallScope`](super::symbol_table::CallScope)).

